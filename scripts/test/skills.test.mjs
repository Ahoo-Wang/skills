import assert from "node:assert/strict";
import { execFileSync, spawnSync } from "node:child_process";
import fs from "node:fs";
import os from "node:os";
import path from "node:path";
import { after, describe, test } from "node:test";
import { fileURLToPath } from "node:url";
import { pluginVersion } from "../lib/catalog.mjs";
import { globMatch } from "../lib/fsutil.mjs";

const CLI = path.join(path.dirname(fileURLToPath(import.meta.url)), "..", "skills.mjs");
const TMP = fs.mkdtempSync(path.join(os.tmpdir(), "skills-test-"));
after(() => fs.rmSync(TMP, { recursive: true, force: true }));

let counter = 0;
const tmpDir = (name) => fs.mkdtempSync(path.join(TMP, `${name}-${counter++}-`));

function write(file, content) {
  fs.mkdirSync(path.dirname(file), { recursive: true });
  fs.writeFileSync(file, content);
}
const readJson = (file) => JSON.parse(fs.readFileSync(file, "utf8"));
const skillMd = (name, body = "Body.\n") => `---\nname: ${name}\ndescription: ${name} skill\n---\n\n${body}`;
const git = (dir, ...args) =>
  execFileSync("git", ["-C", dir, "-c", "user.name=t", "-c", "user.email=t@t", ...args], { encoding: "utf8" });

/** An upstream repository: skills/<name>/SKILL.md plus skills/plugins.json. */
function upstream(name, { skills, plugins }) {
  const dir = path.join(tmpDir("up"), name);
  for (const [skill, body] of Object.entries(skills)) write(path.join(dir, "skills", skill, "SKILL.md"), skillMd(skill, body));
  write(path.join(dir, "skills", "plugins.json"), JSON.stringify({ schemaVersion: 1, plugins }));
  git(dir, "init", "-q", "-b", "main");
  commit(dir);
  return dir;
}
function commit(dir) {
  git(dir, "add", "-A");
  git(dir, "commit", "-qm", "change");
}
const plugin = (name, skills = { include: ["*"] }, extra = {}) => ({ name, description: `${name} plugin`, skills, ...extra });

/** The aggregate repository this tool runs in. */
function aggregate(sources, { local = false } = {}) {
  const root = tmpDir("agg");
  write(
    path.join(root, "repos.json"),
    JSON.stringify({ repos: Object.entries(sources).map(([name, url]) => ({ name, url, branch: "main" })) }),
  );
  write(
    path.join(root, "package.json"),
    JSON.stringify({ name: "test-skills", description: "Test marketplace", author: { name: "Tester" }, license: "MIT" }),
  );
  write(
    path.join(root, "README.md"),
    "# Test\n\n<!-- catalog:start (generated by `npm run build`; do not edit) -->\n<!-- catalog:end -->\n",
  );
  if (local) localPlugin(root, "local-plugin", "local-skill");
  return root;
}
function localPlugin(root, name, skill) {
  const dir = path.join(root, "plugins", name);
  write(path.join(dir, ".claude-plugin", "plugin.json"), JSON.stringify({ name, description: "Local" }, null, 2));
  write(
    path.join(dir, ".codex-plugin", "plugin.json"),
    JSON.stringify(
      {
        name,
        description: "Local",
        skills: "./skills/",
        interface: { displayName: "Local", shortDescription: "Local", longDescription: "Local", defaultPrompt: "Go" },
      },
      null,
      2,
    ),
  );
  write(path.join(dir, "skills", skill, "SKILL.md"), skillMd(skill));
}

function run(command, root, env = {}) {
  const result = spawnSync(process.execPath, [CLI, command, "--root", root], {
    encoding: "utf8",
    env: { ...process.env, CODEX_PLUGIN_VALIDATOR: "", ...env },
  });
  return { status: result.status, output: result.stdout + result.stderr };
}
function ok(command, root) {
  const result = run(command, root);
  assert.equal(result.status, 0, result.output);
  return result.output;
}
const version = (root, name, kind = "claude") =>
  readJson(path.join(root, "plugins", name, `.${kind}-plugin`, "plugin.json")).version;

describe("sync", () => {
  test("mirrors declared skills and derives manifests, marketplaces, lock and README", () => {
    const up = upstream("Alpha", {
      skills: { "alpha-one": "Line\n  \n\t\nEnd\n", "alpha-two": "Two\n", "alpha-workspace": "Scratch\n" },
      plugins: [plugin("alpha-skills", { include: ["*"], exclude: ["*-workspace"] }, { keywords: ["a"] })],
    });
    const root = aggregate({ Alpha: up }, { local: true });
    ok("sync", root);

    const skills = path.join(root, "plugins", "alpha-skills", "skills");
    assert.deepEqual(fs.readdirSync(skills).sort(), ["alpha-one", "alpha-two"]);
    assert.match(fs.readFileSync(path.join(skills, "alpha-one", "SKILL.md"), "utf8"), /Line\n\n\nEnd\n$/);

    const claude = readJson(path.join(root, "plugins", "alpha-skills", ".claude-plugin", "plugin.json"));
    const codex = readJson(path.join(root, "plugins", "alpha-skills", ".codex-plugin", "plugin.json"));
    assert.deepEqual(Object.keys(claude).slice(0, 3), ["name", "description", "version"]);
    assert.match(claude.version, /^1\.0\.0\+[0-9a-f]{12}$/);
    assert.equal(codex.version, claude.version);
    assert.equal(claude.author.name, "Tester");
    assert.equal(codex.interface.displayName, "Alpha Skills");

    const marketplace = readJson(path.join(root, ".claude-plugin", "marketplace.json"));
    assert.deepEqual(marketplace.plugins.map((p) => p.name), ["alpha-skills", "local-plugin"]);
    assert.ok(marketplace.plugins.every((p) => !("version" in p)));
    const codexMarketplace = readJson(path.join(root, ".agents", "plugins", "marketplace.json"));
    assert.deepEqual(codexMarketplace.plugins[0].source, { source: "local", path: "./plugins/alpha-skills" });

    const lock = readJson(path.join(root, "skills.lock.json"));
    assert.equal(lock.sources[0].commit, git(up, "rev-parse", "HEAD").trim());
    assert.deepEqual(Object.keys(lock.sources[0].skills), ["alpha-one", "alpha-two"]);

    const readme = fs.readFileSync(path.join(root, "README.md"), "utf8");
    assert.match(readme, /\| `alpha-skills` \| \[Alpha\]\(.*\) \| \[`alpha-one`\]\(\.\/plugins\/alpha-skills\/skills\/alpha-one\/SKILL\.md\)/);
    assert.match(readme, /\| `local-plugin` \| This repository \|/);

    ok("check", root);
  });

  test("changes nothing when any source fails", () => {
    const good = upstream("Good", { skills: { "good-skill": "x" }, plugins: [plugin("good-skills")] });
    const root = aggregate({ Good: good, Missing: path.join(TMP, "does-not-exist") });
    const result = run("sync", root);
    assert.equal(result.status, 1);
    assert.match(result.output, /Missing: cannot clone/);
    assert.ok(!fs.existsSync(path.join(root, "plugins")));
    assert.ok(!fs.existsSync(path.join(root, "skills.lock.json")));
  });

  const failures = {
    "a missing plugins.json": () => {
      const dir = upstream("NoMeta", { skills: { "x-skill": "x" }, plugins: [] });
      fs.rmSync(path.join(dir, "skills", "plugins.json"));
      commit(dir);
      return [{ NoMeta: dir }, /skills\/plugins\.json not found/];
    },
    "a skill name shared by two sources": () => [
      {
        A: upstream("A", { skills: { shared: "a" }, plugins: [plugin("a-skills")] }),
        B: upstream("B", { skills: { shared: "b" }, plugins: [plugin("b-skills")] }),
      },
      /Skill shared is in both A and B/,
    ],
    "a plugin declared by two sources": () => [
      {
        A: upstream("A", { skills: { "a-skill": "a" }, plugins: [plugin("same")] }),
        B: upstream("B", { skills: { "b-skill": "b" }, plugins: [plugin("same")] }),
      },
      /Plugin same is declared by both A and B/,
    ],
    "an upstream skill in no plugin": () => [
      { A: upstream("A", { skills: { kept: "k", orphan: "o" }, plugins: [plugin("a-skills", ["kept"])] }) },
      /A: skills not in any plugin: orphan/,
    ],
    "a plugin listing a skill that does not exist": () => [
      { A: upstream("A", { skills: { real: "r" }, plugins: [plugin("a-skills", ["real", "ghost"])] }) },
      /does not have: ghost/,
    ],
  };
  for (const [name, setup] of Object.entries(failures)) {
    test(`fails on ${name}`, () => {
      const [sources, message] = setup();
      const result = run("sync", aggregate(sources));
      assert.equal(result.status, 1);
      assert.match(result.output, message);
    });
  }

  test("refuses a source plugin that clashes with a local plugin", () => {
    const root = aggregate({ A: upstream("A", { skills: { "a-skill": "a" }, plugins: [plugin("local-plugin")] }) }, { local: true });
    const result = run("sync", root);
    assert.equal(result.status, 1);
    assert.match(result.output, /clashes with the local plugin plugins\/local-plugin/);
    assert.ok(fs.existsSync(path.join(root, "plugins", "local-plugin", "skills", "local-skill")));
  });

  test("keeps the lock when only upstream commits moved, and versions follow content", () => {
    const a = upstream("A", { skills: { "a-skill": "a" }, plugins: [plugin("a-skills")] });
    const b = upstream("B", { skills: { "b-skill": "b" }, plugins: [plugin("b-skills")] });
    const root = aggregate({ A: a, B: b });
    ok("sync", root);
    const lock = fs.readFileSync(path.join(root, "skills.lock.json"), "utf8");
    const [va, vb] = [version(root, "a-skills"), version(root, "b-skills")];

    write(path.join(a, "src", "main.txt"), "code\n");
    commit(a);
    assert.match(ok("sync", root), /no upstream content changes[\s\S]*Derived files are up to date/);
    assert.equal(fs.readFileSync(path.join(root, "skills.lock.json"), "utf8"), lock);

    fs.appendFileSync(path.join(a, "skills", "a-skill", "SKILL.md"), "More.\n");
    commit(a);
    ok("sync", root);
    assert.equal(readJson(path.join(root, "skills.lock.json")).sources[0].commit, git(a, "rev-parse", "HEAD").trim());
    assert.notEqual(version(root, "a-skills"), va);
    assert.equal(version(root, "b-skills"), vb);
    assert.equal(version(root, "a-skills", "codex"), version(root, "a-skills"));
  });

  test("removes plugins and skills that upstream dropped, keeping local plugins", () => {
    const a = upstream("A", { skills: { one: "1", two: "2" }, plugins: [plugin("a-skills", ["one"]), plugin("a-extra", ["two"])] });
    const root = aggregate({ A: a }, { local: true });
    ok("sync", root);
    assert.ok(fs.existsSync(path.join(root, "plugins", "a-extra")));

    fs.rmSync(path.join(a, "skills", "two"), { recursive: true });
    write(path.join(a, "skills", "plugins.json"), JSON.stringify({ schemaVersion: 1, plugins: [plugin("a-skills")] }));
    commit(a);
    ok("sync", root);
    assert.ok(!fs.existsSync(path.join(root, "plugins", "a-extra")));
    assert.ok(fs.existsSync(path.join(root, "plugins", "local-plugin")));
    ok("check", root);
  });
});

describe("check", () => {
  function synced() {
    const root = aggregate(
      { A: upstream("A", { skills: { "a-skill": "a" }, plugins: [plugin("a-skills")] }) },
      { local: true },
    );
    ok("sync", root);
    return root;
  }
  const fails = (root, message) => {
    const result = run("check", root);
    assert.equal(result.status, 1, result.output);
    assert.match(result.output, message);
  };

  test("rejects hand edits to generated skills, even after build", () => {
    const root = synced();
    fs.appendFileSync(path.join(root, "plugins", "a-skills", "skills", "a-skill", "SKILL.md"), "edit\n");
    ok("build", root);
    fails(root, /a-skills\/a-skill differs from upstream A/);
  });

  test("rejects a stale local plugin version until build restamps it", () => {
    const root = synced();
    const before = version(root, "local-plugin");
    fs.appendFileSync(path.join(root, "plugins", "local-plugin", "skills", "local-skill", "SKILL.md"), "more\n");
    fails(root, /local-plugin\/\.claude-plugin\/plugin\.json is out of date/);
    ok("build", root);
    assert.notEqual(version(root, "local-plugin"), before);
    ok("check", root);
  });

  test("rejects an edited marketplace or README catalog", () => {
    const root = synced();
    write(path.join(root, ".claude-plugin", "marketplace.json"), "{}\n");
    const readme = path.join(root, "README.md");
    fs.writeFileSync(readme, fs.readFileSync(readme, "utf8").replace("a-skill", "b-skill"));
    fails(root, /marketplace\.json is out of date[\s\S]*README\.md is out of date/);
  });

  test("rejects malformed skills", () => {
    const root = synced();
    write(path.join(root, "plugins", "local-plugin", "skills", "bad", "SKILL.md"), skillMd("not-bad"));
    write(path.join(root, "plugins", "local-plugin", "skills", "bare", "SKILL.md"), "No frontmatter\n");
    ok("build", root);
    fails(root, /name "not-bad" must equal the directory name "bad"[\s\S]*bare\/SKILL\.md: missing YAML frontmatter/);
  });

  test("generates the site when docs/CNAME exists and rejects edits to it", () => {
    const root = synced();
    write(path.join(root, "docs", "CNAME"), "skills.example.test\n");
    ok("build", root);
    const page = path.join(root, "docs", "zh-CN", "index.html");
    assert.match(fs.readFileSync(page, "utf8"), /<link rel="canonical" href="https:\/\/skills\.example\.test\/zh-CN\/">/);
    assert.match(fs.readFileSync(path.join(root, "docs", "index.html"), "utf8"), /id="a-skills"[\s\S]*a-skill skill/);
    fs.appendFileSync(page, "<!-- edit -->");
    fails(root, /docs\/zh-CN\/index\.html is out of date/);
  });

  test("rejects a local plugin without both manifests", () => {
    const root = synced();
    fs.rmSync(path.join(root, "plugins", "local-plugin", ".codex-plugin"), { recursive: true });
    fails(root, /Local plugin local-plugin is missing \.codex-plugin\/plugin\.json/);
  });
});

describe("plugin version", () => {
  test("matches the established content hash, ignoring each manifest's own version", () => {
    const dir = tmpDir("golden");
    const claude = { name: "p", description: "Demo", version: "0.0.1", keywords: ["x"] };
    const codex = { name: "p", skills: "./skills/", interface: { displayName: "P" } };
    write(path.join(dir, ".claude-plugin", "plugin.json"), JSON.stringify(claude));
    write(path.join(dir, ".codex-plugin", "plugin.json"), JSON.stringify(codex));
    write(path.join(dir, "skills", "demo", "SKILL.md"), "---\nname: demo\ndescription: Demo skill\n---\n\nBody é\n");
    write(path.join(dir, "skills", "demo", "references", "a.md"), "ref\n");
    fs.symlinkSync("../SKILL.md", path.join(dir, "skills", "demo", "references", "link.md"));
    // Value produced by the original shell implementation for this tree.
    assert.equal(pluginVersion(dir, claude, codex), "1.0.0+218b1b1f136c");
    assert.equal(pluginVersion(dir, { ...claude, version: "9" }, codex), "1.0.0+218b1b1f136c");
  });

  test("glob selectors behave like shell case patterns", () => {
    assert.ok(globMatch("*-workspace", "wow-workspace"));
    assert.ok(!globMatch("*-workspace", "wow-develop"));
    assert.ok(globMatch("wow-?ev*", "wow-develop"));
    assert.ok(globMatch("[ab]-skill", "b-skill"));
    assert.ok(!globMatch("[!ab]-skill", "a-skill"));
    assert.ok(globMatch("a.b", "a.b") && !globMatch("a.b", "axb"));
  });
});
