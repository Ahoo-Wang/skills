// The catalog model: which plugins exist, what they contain, and every file
// that is derived from them (plugin manifests, marketplaces, README tables).
//
// Everything here is a pure function of the repository state, so `build`
// writes the derived files and `check` re-derives them and compares.
import fs from "node:fs";
import path from "node:path";
import {
  assertName,
  compareBytes,
  fail,
  formatJson,
  globMatch,
  listDirs,
  readJson,
  sortKeysDeep,
  treeHash,
} from "./fsutil.mjs";

export const PATHS = {
  repos: "repos.json",
  lock: "skills.lock.json",
  plugins: "plugins",
  claudeMarketplace: ".claude-plugin/marketplace.json",
  codexMarketplace: ".agents/plugins/marketplace.json",
  package: "package.json",
  readmes: { "README.md": "en", "README.zh-CN.md": "zh-CN" },
};

const CLAUDE_MANIFEST = ".claude-plugin/plugin.json";
const CODEX_MANIFEST = ".codex-plugin/plugin.json";
const VERSION_CORE = "1.0.0+";
const CATALOG_START = "<!-- catalog:start (generated by `npm run build`; do not edit) -->";
const CATALOG_END = "<!-- catalog:end -->";

/** jq's `a // b`: fall back when the value is null, undefined or false. */
const or = (value, fallback) => (value === null || value === undefined || value === false ? fallback : value);

const isEmpty = (value) => value === "" || (Array.isArray(value) && value.length === 0);
const compact = (object) => Object.fromEntries(Object.entries(object).filter(([, value]) => !isEmpty(value)));

const titleWords = (name) =>
  name
    .split("-")
    .map((word) => word.slice(0, 1).toUpperCase() + word.slice(1))
    .join(" ");

const codexCategory = (category) => (category === "development" ? "Development" : category);

export function readLock(root) {
  const file = path.join(root, PATHS.lock);
  return fs.existsSync(file) ? readJson(file) : { sources: [] };
}

/** Marketplace-wide defaults, taken from package.json. */
export function readDefaults(root) {
  const file = path.join(root, PATHS.package);
  const pkg = fs.existsSync(file) ? readJson(file) : {};
  const repository = pkg.repository && typeof pkg.repository === "object" ? pkg.repository.url : pkg.repository;
  return {
    marketplaceName: or(pkg.name, "ahoo-skills"),
    marketplaceDisplayName: or(pkg.displayName, "Ahoo Skills"),
    description: or(pkg.description, ""),
    author: or(pkg.author, { name: "Ahoo Wang" }),
    homepage: or(pkg.homepage, "https://github.com/Ahoo-Wang/skills"),
    repository: or(repository, "https://github.com/Ahoo-Wang/skills"),
    license: or(pkg.license, "Apache-2.0"),
  };
}

/** Resolves a plugin's `skills` selector against the skills a source offers. */
export function resolveSkills(selector, available, pluginName) {
  let names;
  if (Array.isArray(selector)) {
    names = [...new Set(selector)];
    const missing = names.filter((name) => !available.includes(name));
    if (missing.length) fail(`Plugin ${pluginName} lists skills its source does not have: ${missing.join(", ")}`);
  } else {
    const include = or(selector?.include, ["*"]);
    const exclude = or(selector?.exclude, ["*-workspace"]);
    names = available.filter(
      (name) => include.some((p) => globMatch(p, name)) && !exclude.some((p) => globMatch(p, name)),
    );
  }
  if (names.length === 0) fail(`Plugin ${pluginName} has no skills`);
  return names.map((name) => assertName(name, "skill")).sort(compareBytes);
}

export function claudeManifest(meta, defaults) {
  return compact({
    name: meta.name,
    description: or(meta.description, ""),
    author: or(meta.author, defaults.author),
    homepage: or(meta.homepage, defaults.homepage),
    repository: or(meta.repository, defaults.repository),
    license: or(meta.license, defaults.license),
    keywords: or(meta.keywords, []),
  });
}

export function codexManifest(meta, defaults) {
  const ui = or(meta.interface, {});
  const author = or(meta.author, defaults.author);
  const homepage = or(meta.homepage, defaults.homepage);
  const displayName = or(ui.displayName, or(ui.display_name, titleWords(meta.name)));
  return compact({
    name: meta.name,
    description: or(meta.description, ""),
    author,
    homepage,
    repository: or(meta.repository, defaults.repository),
    license: or(meta.license, defaults.license),
    keywords: or(meta.keywords, []),
    skills: "./skills/",
    interface: compact({
      displayName,
      shortDescription: or(ui.shortDescription, or(ui.short_description, meta.description)),
      longDescription: or(ui.longDescription, or(ui.long_description, meta.description)),
      developerName: or(ui.developerName, or(ui.developer_name, or(author?.name, defaults.author.name))),
      category: codexCategory(or(ui.category, or(meta.category, "Development"))),
      capabilities: or(ui.capabilities, ["Skills"]),
      websiteURL: homepage,
      defaultPrompt: or(ui.defaultPrompt, or(ui.default_prompt, `Help me use ${displayName}.`)),
      brandColor: or(ui.brandColor, or(ui.brand_color, "")),
    }),
  });
}

/** Puts `version` third, after name and description. */
function withVersion(manifest, version) {
  const entries = Object.entries(manifest).filter(([key]) => key !== "version");
  entries.splice(2, 0, ["version", version]);
  return Object.fromEntries(entries);
}

function withoutVersion(manifest) {
  const { version, ...rest } = manifest;
  return rest;
}

/**
 * The version is derived from the plugin's files, both manifests counted
 * without their own `version`. It changes exactly when the plugin's content
 * does, which is when Claude Code and Codex should reinstall it. The fixed
 * 1.0.0 core keeps it semver-valid and above legacy 0.x Codex caches.
 */
export function pluginVersion(pluginDir, claude, codex) {
  const hash = treeHash(pluginDir, {
    [`./${CLAUDE_MANIFEST}`]: formatJson(sortKeysDeep(withoutVersion(claude))),
    [`./${CODEX_MANIFEST}`]: formatJson(sortKeysDeep(withoutVersion(codex))),
  });
  return VERSION_CORE + hash.slice(0, 12);
}

/**
 * Every plugin in the marketplace: generated ones come from the lock file,
 * local ones are any other directory under plugins/.
 */
export function loadPlugins(root) {
  const defaults = readDefaults(root);
  const lock = readLock(root);
  const plugins = [];
  const owner = new Map();

  for (const source of lock.sources) {
    const available = Object.keys(source.skills).sort(compareBytes);
    for (const meta of source.plugins) {
      const name = assertName(meta.name, "plugin");
      if (owner.has(name)) fail(`Plugin ${name} is declared by both ${owner.get(name)} and ${source.name}`);
      owner.set(name, source.name);
      if (!meta.description) fail(`Plugin ${name} from ${source.name} has no description`);
      plugins.push({
        name,
        kind: "generated",
        source,
        meta,
        skills: resolveSkills(meta.skills, available, name),
        claude: claudeManifest(meta, defaults),
        codex: codexManifest(meta, defaults),
      });
    }
  }

  for (const name of listDirs(path.join(root, PATHS.plugins))) {
    if (owner.has(name)) continue;
    const dir = path.join(root, PATHS.plugins, name);
    const manifest = (file) => {
      const abs = path.join(dir, file);
      if (!fs.existsSync(abs)) fail(`Local plugin ${name} is missing ${file}`);
      return readJson(abs);
    };
    plugins.push({
      name,
      kind: "local",
      skills: listDirs(path.join(dir, "skills")),
      claude: manifest(CLAUDE_MANIFEST),
      codex: manifest(CODEX_MANIFEST),
    });
  }

  plugins.sort((a, b) => compareBytes(a.name, b.name));
  return { defaults, lock, plugins };
}

function claudeMarketplace(defaults, plugins) {
  return compact({
    $schema: "https://json.schemastore.org/claude-code-marketplace.json",
    name: defaults.marketplaceName,
    description: defaults.description,
    owner: defaults.author,
    plugins: plugins.map(({ name, claude }) =>
      compact({
        name: claude.name,
        description: claude.description,
        author: claude.author,
        homepage: claude.homepage,
        repository: claude.repository,
        license: claude.license,
        keywords: or(claude.keywords, []),
        source: `./${PATHS.plugins}/${name}`,
        category: or(claude.category, "development"),
      }),
    ),
  });
}

function codexMarketplace(defaults, plugins) {
  return {
    name: defaults.marketplaceName,
    interface: { displayName: defaults.marketplaceDisplayName },
    plugins: plugins.map((plugin) => {
      const policy = plugin.kind === "generated" ? or(plugin.meta.policy, {}) : {};
      const category =
        plugin.kind === "generated"
          ? or(plugin.meta.interface?.category, or(plugin.meta.category, "Development"))
          : or(plugin.codex.interface?.category, "Development");
      return {
        name: plugin.name,
        source: { source: "local", path: `./${PATHS.plugins}/${plugin.name}` },
        policy: {
          installation: or(policy.installation, "AVAILABLE"),
          authentication: or(policy.authentication, "ON_INSTALL"),
        },
        category: codexCategory(category),
      };
    }),
  };
}

const README_TEXT = {
  en: { header: "| Plugin | Source | Skills |", local: "This repository", sep: ", " },
  "zh-CN": { header: "| 插件 | 来源 | Skills |", local: "本仓库", sep: "、" },
};

function renderCatalog(plugins, lang) {
  const text = README_TEXT[lang];
  const rows = plugins.map((plugin) => {
    const source =
      plugin.kind === "generated"
        ? `[${plugin.source.name}](${plugin.source.url.replace(/\.git$/, "")})`
        : text.local;
    const skills = plugin.skills
      .map((skill) => `[\`${skill}\`](./${PATHS.plugins}/${plugin.name}/skills/${skill}/SKILL.md)`)
      .join(text.sep);
    return `| \`${plugin.name}\` | ${source} | ${skills} |`;
  });
  return [CATALOG_START, text.header, "|---|---|---|", ...rows, CATALOG_END].join("\n");
}

function withCatalog(readme, file, catalog) {
  const start = readme.indexOf(CATALOG_START);
  const end = readme.indexOf(CATALOG_END);
  if (start === -1 || end < start) fail(`${file} has no catalog markers; add "${CATALOG_START}" and "${CATALOG_END}"`);
  return readme.slice(0, start) + catalog + readme.slice(end + CATALOG_END.length);
}

/**
 * Every derived file as { relative path: expected content }. Plugin skill
 * directories are not derived here: they are mirrored by `sync` (generated)
 * or written by hand (local).
 */
export function deriveFiles(root, model = loadPlugins(root)) {
  const { defaults, plugins } = model;
  const files = new Map();

  for (const plugin of plugins) {
    const dir = path.join(PATHS.plugins, plugin.name);
    const version = pluginVersion(path.join(root, dir), plugin.claude, plugin.codex);
    plugin.claude = withVersion(plugin.claude, version);
    plugin.codex = withVersion(plugin.codex, version);
    files.set(path.join(dir, CLAUDE_MANIFEST), formatJson(plugin.claude));
    files.set(path.join(dir, CODEX_MANIFEST), formatJson(plugin.codex));
  }

  files.set(PATHS.claudeMarketplace, formatJson(claudeMarketplace(defaults, plugins)));
  files.set(PATHS.codexMarketplace, formatJson(codexMarketplace(defaults, plugins)));

  for (const [file, lang] of Object.entries(PATHS.readmes)) {
    const abs = path.join(root, file);
    if (!fs.existsSync(abs)) continue;
    files.set(file, withCatalog(fs.readFileSync(abs, "utf8"), file, renderCatalog(plugins, lang)));
  }
  return files;
}

export function writeDerivedFiles(root, files) {
  const changed = [];
  for (const [rel, content] of files) {
    const abs = path.join(root, rel);
    if (fs.existsSync(abs) && fs.readFileSync(abs, "utf8") === content) continue;
    fs.mkdirSync(path.dirname(abs), { recursive: true });
    fs.writeFileSync(abs, content);
    changed.push(rel);
  }
  return changed;
}
